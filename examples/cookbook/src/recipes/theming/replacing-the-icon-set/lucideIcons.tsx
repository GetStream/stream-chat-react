import { createIcon, type IconComponent, type IconName } from 'stream-chat-react';

type LucideOptions = {
  /**
   * Draws the shape solid. Lucide draws outlines by default. Only plain shapes are filled (play,
   * pause, video, message bubble): a Lucide icon with marks inside, such as the eye's pupil, the
   * alerts' exclamation mark or the thread's arrow, would lose them, so those `…Fill` icons stay
   * outlines.
   */
  filled?: boolean;
  /** Flips the icon in right-to-left layouts, as the SDK does for its arrows. */
  mirrorInRtl?: boolean;
};

/**
 * Wraps a Lucide icon in the SDK's icon. `createIcon` derives the SDK's classes from the name
 * (`IconSend` → `str-chat__icon--send`), so the SDK's styles for that icon still apply. Lucide
 * draws on a 24×24 grid, so the SDK's svg gets that viewBox and Lucide's svg fills it.
 */
const fromLucide = (
  name: IconName,
  Lucide: LucideIcon,
  { filled = false, mirrorInRtl = false }: LucideOptions = {},
) =>
  createIcon(
    name,
    filled ? (
      <Lucide fill='currentColor' />
    ) : (
      <Lucide className='cookbook-lucide-outline' />
    ),
    { viewBox: '0 0 24 24', ...(mirrorInRtl && { 'data-rtl-mirror': '' }) },
  );

